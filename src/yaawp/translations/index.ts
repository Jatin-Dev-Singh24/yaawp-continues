export const translate = (key: TranslationKey, langCode?: string): string => {
  const code = (langCode || DEFAULT_LANGUAGE_CODE).toLowerCase();
  const dict = TRANSLATIONS[code];
  if (dict && dict[key]) {
    return dict[key]!;
  }
  // Fallback to English
  return en[key] || key;
};
